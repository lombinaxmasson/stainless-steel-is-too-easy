package com.lombinaxmasson.ssite.chemistry;

import static com.lombinaxmasson.ssite.chemistry.ChemistryRecipes.dust;
import static com.lombinaxmasson.ssite.chemistry.ChemistryRecipes.item;
import static com.lombinaxmasson.ssite.chemistry.ChemistryRecipes.row;
import static com.lombinaxmasson.ssite.chemistry.ChemistryRecipes.vanillaItem;

/** M6 nuclear hydrometallurgy and the N-01 thorium fuel fabrication route. */
public final class NuclearRecipes {
    private NuclearRecipes() {}

    static void add() {
        uraniumThoriumTbp();
        thoriumFuel();
    }

    private static void uraniumThoriumTbp() {
        // The autoclave takes one fluid input and needs two item stacks, so the oxidative
        // acid leach runs in the calciner like the monazite and xenotime digest rows.
        row("gt.recipe.calciner", "nuclear/pitchblende-leach")
                .in(dust("Pitchblende", 2))
                .out(dust("ThoriumConcentrate", 1), dust("Lead", 1))
                .fluidIn("GenLiquid_SulfuricAcid", 2000, "GenGas_HydrogenPeroxide", 1000)
                .fluidOut("GenLiquid_UranylSulfateSolution", 2000)
                .add(240, 64);

        row("gt.recipe.calciner", "nuclear/uraninite-leach")
                .in(dust("Uraninite", 2))
                .fluidIn("GenLiquid_SulfuricAcid", 2000, "GenGas_HydrogenPeroxide", 1000)
                .fluidOut("GenLiquid_UranylSulfateSolution", 2500)
                .add(200, 64);

        // The resin stays in the machine and is regenerated by the ammonia strip.
        row("gt.recipe.mixer", "nuclear/resin-yellowcake")
                .in(dust("AnionExchangeResin", 1))
                .keep(0)
                .fluidIn("GenLiquid_UranylSulfateSolution", 4000, "GenGas_Ammonia", 2000)
                .out(dust("Yellowcake", 1))
                .fluidOut("Dirty_Water", 3000)
                .add(240, 48);

        row("gt.recipe.mixer", "nuclear/yellowcake-dissolve")
                .in(dust("Yellowcake", 1))
                .fluidIn("GenLiquid_NitricAcid", 3000)
                .fluidOut("GenLiquid_UranylNitrateSolution", 2000, "Dirty_Water", 1000)
                .add(160, 48);

        row("gt.recipe.mixer", "nuclear/tbp-uranium")
                .fluidIn("GenLiquid_UranylNitrateSolution", 2000, "GenLiquid_TributylPhosphate", 1000)
                .fluidOut("GenLiquid_TbpUraniumExtract", 1000, "Dirty_Water", 2000)
                .add(160, 64);

        row("gt.recipe.mixer", "nuclear/uranium-strip")
                .fluidIn("GenLiquid_TbpUraniumExtract", 1000, "DistW", 1000)
                .fluidOut("GenLiquid_PureUranylNitrate", 2000, "GenLiquid_TributylPhosphate", 950)
                .add(160, 48);

        row("gt.recipe.calciner", "nuclear/uo2-reduction")
                .fluidIn("GenLiquid_PureUranylNitrate", 2000, "GenGas_Hydrogen", 1000)
                .out(dust("UraniumDioxide", 1))
                .fluidOut("GenGas_NitrogenDioxide", 2000, "Steam", 1000, "Oxygen", 500)
                .add(200, 64);

        row("gt.recipe.calciner", "nuclear/uf4")
                .in(dust("UraniumDioxide", 1))
                .fluidIn("GenGas_HydrogenFluoride", 4000)
                .out(dust("UraniumTetrafluoride", 1))
                .fluidOut("DistW", 2000)
                .add(160, 64);

        row("gt.recipe.mixer", "nuclear/thorium-dissolve")
                .in(dust("ThoriumConcentrate", 1))
                .fluidIn("GenLiquid_NitricAcid", 3000)
                .fluidOut("GenLiquid_ThoriumNitrateSolution", 2000, "Dirty_Water", 1000)
                .add(160, 48);

        row("gt.recipe.mixer", "nuclear/tbp-thorium")
                .fluidIn("GenLiquid_ThoriumNitrateSolution", 2000, "GenLiquid_TributylPhosphate", 1000)
                .fluidOut("GenLiquid_TbpThoriumExtract", 1000, "Dirty_Water", 2000)
                .add(160, 64);

        row("gt.recipe.mixer", "nuclear/thorium-strip")
                .fluidIn("GenLiquid_TbpThoriumExtract", 1000, "DistW", 1000)
                .fluidOut("GenLiquid_PureThoriumNitrate", 2000, "GenLiquid_TributylPhosphate", 950)
                .add(160, 48);

        // The calciner needs two input stacks; drying accepts the single nitrate stream.
        row("gt.recipe.drying", "nuclear/tho2")
                .fluidIn("GenLiquid_PureThoriumNitrate", 2000)
                .out(dust("ThoriumDioxide", 1))
                .fluidOut("GenGas_NitrogenDioxide", 4000, "Oxygen", 2000)
                .add(200, 64);

        row("gt.recipe.calciner", "nuclear/thorium")
                .in(dust("ThoriumDioxide", 1), dust("Calcium", 2))
                .out(dust("Thorium", 1), dust("Quicklime", 2))
                .add(240, 96);
    }

    private static void thoriumFuel() {
        // The host canner already turns a thorium stick plus an empty rod into the host fuel
        // rod; the industrial route presses and sinters the oxide before encapsulation.
        // The press map requires two item inputs; graphite is the die-wall lubricant, as in M9-03.
        row("gt.recipe.press", "nuclear/fuel-thorium-compact")
                .in(dust("ThoriumDioxide", 1), item("dustTiny", "Graphite", 1))
                .out(dust("ThoriumFuelCompact", 1))
                .add(120, 32);

        // The port has no placeable Calciner block; the Roasting Oven uses the reachable
        // gt.recipe.roaster map and is the host's heat-treatment machine for this step.
        // Tier 1 accepts at most 64 HU/t, so the row uses 32 HU/t instead of M9-03's EU value.
        row("gt.recipe.roaster", "nuclear/fuel-thorium-sinter")
                .in(dust("ThoriumFuelCompact", 1))
                .out(dust("ThoriumFuelPellet", 1))
                .fluidIn("GenGas_Argon", 1000)
                .add(240, 32);

        // The output is the host item id, so reactor physics and depletion stay host-owned.
        // Canner is an EU machine; the row keeps the host rod recipe's 16t / 16 EU/t pace.
        row("gt.recipe.canner", "nuclear/fuel-thorium-encapsulate")
                .in(dust("ThoriumFuelPellet", 1), vanillaItem("gt6ce:reactor_rod_9201", 1))
                .out(vanillaItem("gt6ce:fuel_rod_th_232", 1))
                .add(16, 16);
    }
}
